"""Strict validation for hook-free profiles produced by the manual form.

Imported profiles have a separate review/confirmation flow; this grammar is
deliberately limited to the fields generated by NetMon's manual form.
"""

import base64
import binascii
import ipaddress
import re
import unicodedata

from netmon.core import nm_ownership


def validate_single_line(value):
    if not isinstance(value, str) or any(
        (c.isspace() and c != " ") or unicodedata.category(c).startswith("C")
        for c in value
    ):
        raise ValueError("Manuelle WireGuard-Felder muessen einzeilig sein.")


def parse_endpoint(value):
    """Return a canonical host and port without DNS lookups or lossy stripping."""
    if not isinstance(value, str) or not value or len(value) > 261:
        raise ValueError("Endpoint fehlt oder ist zu lang (Format host:port).")
    if any(c.isspace() or unicodedata.category(c).startswith("C") for c in value):
        raise ValueError("Endpoint darf keine Leer- oder Steuerzeichen enthalten.")
    if value.startswith("["):
        match = re.fullmatch(r"\[([0-9A-Fa-f:.]+)\]:([0-9]{1,5})", value)
        if not match:
            raise ValueError("Endpoint ungueltig (Format [IPv6]:port).")
        host, port = match.groups()
        try:
            host = str(ipaddress.IPv6Address(host))
        except ValueError as exc:
            raise ValueError("Endpoint-Host ist keine gueltige IPv6-Adresse.") from exc
    else:
        match = re.fullmatch(r"([A-Za-z0-9.-]+):([0-9]{1,5})", value)
        if not match:
            raise ValueError("Endpoint ungueltig (Format host:port).")
        host, port = match.groups()
        try:
            host = str(ipaddress.IPv4Address(host))
        except ValueError:
            dns = host.removesuffix(".")
            if (
                len(dns) > 253
                or re.fullmatch(r"[0-9.]+", dns)
                or any(
                    not re.fullmatch(
                        r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", label
                    )
                    for label in dns.split(".")
                )
            ):
                raise ValueError(
                    "Endpoint-Host ist keine gueltige IP oder DNS-Adresse."
                )
            host = host.lower()
    if not 1 <= int(port) <= 65535:
        raise ValueError("Endpoint-Port muss zwischen 1 und 65535 liegen.")
    return host, str(int(port))


def validate_config(text):
    """Check the exact rendered bytes again before the privileged handoff."""
    error = "Manuelle WireGuard-Konfiguration ist ungueltig."
    if (
        not isinstance(text, str)
        or not 0 < len(text.encode("utf-8")) <= nm_ownership.MAX_CONFIG
        or any(
            c != "\n"
            and (c.isspace() and c != " " or unicodedata.category(c).startswith("C"))
            for c in text
        )
        or nm_ownership.wireguard_hooks(text.encode("utf-8"))
    ):
        raise ValueError(error)
    allowed = {
        "Interface": {"PrivateKey", "Address", "DNS"},
        "Peer": {
            "PublicKey",
            "AllowedIPs",
            "Endpoint",
            "PresharedKey",
            "PersistentKeepalive",
        },
    }
    sections = []
    values = {}
    section = None
    for line in text.split("\n"):
        if not line.strip():
            continue
        if line in ("[Interface]", "[Peer]"):
            section = line[1:-1]
            sections.append(section)
            continue
        key, sep, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if (
            section is None
            or not sep
            or key not in allowed[section]
            or key in values
            or not value
        ):
            raise ValueError(error)
        values[key] = value
    if (
        sections != ["Interface", "Peer"]
        or not {"PrivateKey", "Address", "PublicKey", "AllowedIPs", "Endpoint"}
        <= values.keys()
    ):
        raise ValueError(error)
    try:
        for key in ("PrivateKey", "PublicKey", "PresharedKey"):
            if (
                key in values
                and len(base64.b64decode(values[key], validate=True)) != 32
            ):
                raise ValueError(error)
        for key in ("Address", "AllowedIPs"):
            for token in values[key].split(","):
                ipaddress.ip_network(token.strip(), strict=False)
        if "DNS" in values:
            for token in values["DNS"].split(","):
                candidate = token.strip()
                if candidate.startswith("[") and candidate.endswith("]"):
                    candidate = candidate[1:-1]
                if "%" in candidate:
                    raise ValueError(error)
                ipaddress.ip_address(candidate)
        parse_endpoint(values["Endpoint"])
        if "PersistentKeepalive" in values and (
            not re.fullmatch(r"[0-9]{1,5}", values["PersistentKeepalive"])
            or int(values["PersistentKeepalive"]) > 65535
        ):
            raise ValueError(error)
    except (ValueError, binascii.Error) as exc:
        raise ValueError(error) from exc
